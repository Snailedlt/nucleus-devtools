#!/usr/bin/env node
// The votes on the docs, from the workbench's votes report (votes.json on the testbench's `data` branch, summed daily
// from GoatCounter by its tools/votes-report.mjs), as data/doc-votes.json: per doc part ("doc/<name>": the member's
// doc; "practice/<name>": its AI-written "In practice" part), [👍, 👎] from people and, kept apart, from AIs
// (`ncdev docs vote`, the MCP tool nucleus_vote_doc). core/docvotes.ts reads it: the counts the docs show, and the
// "Verified by people" label (human votes only). The Sync workflow refreshes it daily; the workbench's build uses the
// data branch's newest votes.json directly.
//
//   node scripts/doc-votes.mjs [votes.json path or URL]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = process.argv[2] ?? 'https://raw.githubusercontent.com/Snailedlt/nucleuscoop-handler-testbench/data/votes.json';
let text;
if (/^https?:/.test(src)) {
  const res = await fetch(src);
  if (!res.ok) throw new Error(`doc-votes: ${src} answered ${res.status}; data/doc-votes.json stays.`);
  text = await res.text();
} else text = fs.readFileSync(src, 'utf8');
const report = JSON.parse(text);
// Only a real report replaces the snapshot (empty lists are fine: they clear old counts).
const lists = ['docs', 'practice', 'aiDocs', 'aiPractice'];
if (!report || typeof report !== 'object' || !lists.some((k) => Array.isArray(report[k])) || lists.some((k) => report[k] !== undefined && !Array.isArray(report[k])))
  throw new Error('doc-votes: not a votes report (no vote lists); data/doc-votes.json stays.');
// Every row whole: an id and two counts (whole numbers, 0 or more). One bad row and the snapshot stays.
const count = (n) => Number.isInteger(n) && n >= 0;
for (const k of lists) for (const x of report[k] ?? [])
  if (!x || typeof x.id !== 'string' || !x.id || !count(x.up) || !count(x.down)) throw new Error(`doc-votes: a ${k} row without an id or counts (${JSON.stringify(x)}); data/doc-votes.json stays.`);
const pairs = (list, part) => (list ?? []).filter((x) => x.up > 0 || x.down > 0).map((x) => [`${part}/${x.id}`, [x.up, x.down]]);
const sorted = (entries) => Object.fromEntries(entries.sort((a, b) => a[0].localeCompare(b[0])));
const out = {
  $comment: 'Generated by scripts/doc-votes.mjs from the votes report (testbench data branch votes.json). "<part>/<name>": [up, down]; people and AIs kept apart. Do not edit by hand.',
  takenAt: String(report.takenAt ?? '').slice(0, 10),
  people: sorted([...pairs(report.docs, 'doc'), ...pairs(report.practice, 'practice')]),
  ais: sorted([...pairs(report.aiDocs, 'doc'), ...pairs(report.aiPractice, 'practice')]),
};
const file = path.join(root, 'data', 'doc-votes.json');
const before = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
const next = JSON.stringify(out, null, 1) + '\n';
// Only the date moved: keep the file as it is (no pull request for nothing).
if (before && JSON.stringify({ ...JSON.parse(before), takenAt: '' }) === JSON.stringify({ ...out, takenAt: '' })) console.log('doc-votes: no change.');
else {
  fs.writeFileSync(file, next);
  console.log(`doc-votes: ${Object.keys(out.people).length} parts with people's votes, ${Object.keys(out.ais).length} with AIs' (${out.takenAt}).`);
}
